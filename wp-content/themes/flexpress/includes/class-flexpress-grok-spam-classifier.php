<?php
/**
 * Grok-powered, informational spam screening for casting applications.
 *
 * @package FlexPress
 */

if (!defined('ABSPATH')) {
    exit;
}

class FlexPress_Grok_Spam_Classifier {
    const API_URL = 'https://api.x.ai/v1/chat/completions';
    const DEFAULT_MODEL = 'grok-4.3';

    /**
     * Return a safe, presentation-ready review. Failures deliberately never
     * interrupt a Contact Form 7 submission.
     */
    public function classify_casting_submission($posted_data) {
        $settings = $this->get_settings();

        if (empty($settings['casting_spam_enabled'])) {
            return $this->unreviewed(__('AI screening is disabled.', 'flexpress'));
        }

        if (empty($settings['grok_api_key'])) {
            return $this->unreviewed(__('Grok API key is not configured.', 'flexpress'));
        }

        $payload = $this->build_payload($posted_data);
        if (empty($payload)) {
            return $this->unreviewed(__('No casting fields were available for screening.', 'flexpress'));
        }

        $response = $this->request_verdict($settings['grok_api_key'], $settings['grok_model'], $payload);
        if (is_wp_error($response)) {
            return $this->unreviewed(__('Grok screening was unavailable.', 'flexpress'));
        }

        return $response;
    }

    /** A lightweight request used by the protected settings-page test button. */
    public function test_connection() {
        $settings = $this->get_settings();
        if (empty($settings['grok_api_key'])) {
            return new WP_Error('flexpress_grok_missing_key', __('Save a Grok API key before testing.', 'flexpress'));
        }

        $result = $this->request_verdict($settings['grok_api_key'], $settings['grok_model'], array(
            'test_submission' => 'This is a legitimate test casting application generated by FlexPress.'
        ));

        return is_wp_error($result) ? $result : true;
    }

    private function get_settings() {
        $settings = get_option('flexpress_ai_settings', array());
        return is_array($settings) ? $settings : array();
    }

    private function request_verdict($api_key, $model, $submission) {
        $body = array(
            'model' => $model ?: self::DEFAULT_MODEL,
            'temperature' => 0,
            'messages' => array(
                array(
                    'role' => 'system',
                    'content' => $this->get_system_prompt()
                ),
                array(
                    'role' => 'user',
                    'content' => wp_json_encode(array('casting_submission' => $submission))
                ),
            ),
            'response_format' => array(
                'type' => 'json_schema',
                'json_schema' => array(
                    'name' => 'casting_spam_verdict',
                    'strict' => true,
                    'schema' => array(
                        'type' => 'object',
                        'properties' => array(
                            'classification' => array('type' => 'string', 'enum' => array('legit', 'suspicious', 'spam_troll')),
                            'potential_spam' => array('type' => 'boolean'),
                            'reason' => array('type' => 'string', 'maxLength' => 300),
                        ),
                        'required' => array('classification', 'potential_spam', 'reason'),
                        'additionalProperties' => false,
                    ),
                ),
            ),
        );

        $response = wp_remote_post(self::API_URL, array(
            'headers' => array(
                'Authorization' => 'Bearer ' . $api_key,
                'Content-Type' => 'application/json',
                'User-Agent' => 'FlexPress-Grok-Spam-Screening/1.0',
            ),
            'body' => wp_json_encode($body),
            'timeout' => 8,
            'redirection' => 0,
        ));

        if (is_wp_error($response) || wp_remote_retrieve_response_code($response) < 200 || wp_remote_retrieve_response_code($response) >= 300) {
            return new WP_Error('flexpress_grok_request_failed');
        }

        $response_data = json_decode(wp_remote_retrieve_body($response), true);
        $content = $response_data['choices'][0]['message']['content'] ?? '';
        $result = is_string($content) ? json_decode($content, true) : null;
        $classification = is_array($result) ? ($result['classification'] ?? '') : '';
        $potential_spam = is_array($result) ? ($result['potential_spam'] ?? null) : null;
        $reason = is_array($result) ? ($result['reason'] ?? '') : '';
        $expected_potential_spam = in_array($classification, array('suspicious', 'spam_troll'), true);

        if (
            !in_array($classification, array('legit', 'suspicious', 'spam_troll'), true) ||
            !is_bool($potential_spam) ||
            $potential_spam !== $expected_potential_spam ||
            !is_string($reason) ||
            $reason === ''
        ) {
            return new WP_Error('flexpress_grok_invalid_response');
        }

        return array(
            'status' => 'reviewed',
            'classification' => $classification,
            'potential_spam' => $potential_spam,
            'reason' => $this->limit_text(sanitize_text_field($reason), 300),
        );
    }

    /**
     * Policy distilled from the internal staff review. It deliberately avoids
     * sending that private review or other applicants' data to xAI.
     */
    private function get_system_prompt() {
        return <<<'PROMPT'
You are an internal triage assistant for casting applications to an Australian adult-production studio.

Classify the submitted application using only the supplied fields. Sexual content, adult-industry interest, inexperience, awkward writing, poor grammar, an unusual identity, overseas location, or a small age/stage-age mismatch are not spam by themselves.

Return only the required JSON. Do not browse links, inspect social profiles, infer missing facts, claim prior-submission knowledge, or refer to information outside the application.

Classifications:
- legit: a plausible application with enough coherent or specific detail to merit normal staff review.
- suspicious: a low-quality, contradictory, unusable, or questionable application that should be manually reviewed, but may be genuine.
- spam_troll: a strong likely fake, troll, scam, irrelevant job-seeking submission, or obvious promotional spam.

Set potential_spam to true for suspicious and spam_troll. Set it to false only for legit.

Signals for suspicious:
- Extremely thin, generic, or implausible bio with little supporting detail.
- A malformed, unusable, or generic work/social link, especially when paired with a weak bio.
- Contradictions across the form that materially undermine credibility.
- A submission focused on getting any job rather than a casting application.
- Grand claims with no credible supporting detail.

Signals for spam_troll require strong evidence, such as:
- Obvious joke or troll content.
- Implausible boasts, fabricated-sounding awards/credits, or nonsensical content.
- Multiple independent red flags: an extreme age contradiction (about 15+ years or two+ stage-age bands), crude one-liner, mismatched identity details, missing agreement, or unusable links.
- Clear irrelevant job-seeking spam or malicious/promotional content.

Important safeguards:
- One stage-age band (about 5-8 years) is normal and must not be a spam signal.
- A 10-14 year stage-age gap is not sufficient alone; only treat it as a supporting concern with other evidence.
- Newcomers, private applicants, amateur experience, messy fields, generic social handles, and no adult-industry portfolio can be genuine.
- A named portfolio, Model Mayhem, LinkedIn, Google Drive portfolio, escort directory, OnlyFans profile, Instagram handle, or coherent biography is supportive evidence even if it cannot be verified live.
- A bare site homepage, a social-media homepage, pasted prose in a URL field, or a private Telegram URL is unusable evidence, not automatic spam.
- Overseas location, travel/visa discussion, gender identity, or being female are casting/logistics information, never spam signals.
- Never invent profile activity, link contents, staff comments, prior applications, or duplicate submissions.

Keep reason under 300 characters. State only the strongest observed evidence.
PROMPT;
    }

    private function build_payload($posted_data) {
        if (!is_array($posted_data)) {
            return array();
        }

        $payload = array();
        $payload_size = 0;
        foreach ($posted_data as $key => $value) {
            // CF7 internals do not contribute to spam assessment.
            if (strpos((string) $key, '_wpcf7') === 0 || $key === '_wpnonce') {
                continue;
            }
            if (count($payload) >= 30) {
                break;
            }
            $clean_key = sanitize_key($key);
            if ($clean_key === '') {
                continue;
            }
            $clean_value = $this->limit_value($value);
            $field_size = strlen(wp_json_encode(array($clean_key => $clean_value)));
            // Bound the complete form payload, not merely individual fields.
            if ($payload_size + $field_size > 12000) {
                continue;
            }
            $payload[$clean_key] = $clean_value;
            $payload_size += $field_size;
        }

        return $payload;
    }

    private function limit_value($value) {
        if (is_array($value)) {
            return array_map(array($this, 'limit_value'), array_slice($value, 0, 20));
        }
        if (is_scalar($value)) {
            return $this->limit_text(wp_strip_all_tags((string) $value), 2500);
        }
        return '';
    }

    private function limit_text($text, $limit) {
        return function_exists('mb_substr') ? mb_substr($text, 0, $limit) : substr($text, 0, $limit);
    }

    private function unreviewed($reason) {
        return array(
            'status' => 'unreviewed',
            'classification' => 'unreviewed',
            'potential_spam' => false,
            'reason' => $reason,
        );
    }
}
